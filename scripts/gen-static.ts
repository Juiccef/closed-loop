// Embeds apps/** (console, simulator, shared assets) into the web Lambda bundle as strings.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const APPS = join(ROOT, 'apps');
const OUT = join(ROOT, 'packages', 'api', 'src', 'static.generated.ts');

async function walk(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])));
  return files.flat().filter((f) => /\.(html|js|css|svg|json)$/.test(f));
}

const files: Record<string, string> = {};
for (const f of (await walk(APPS)).sort()) files[relative(APPS, f).split('\\').join('/')] = await readFile(f, 'utf8');
await writeFile(OUT, `// Generated by scripts/gen-static.ts. Do not edit.\nexport const STATIC_FILES: Record<string, string> = ${JSON.stringify(files, null, 0)};\n`);
console.log(`static: ${Object.keys(files).length} files embedded`);
